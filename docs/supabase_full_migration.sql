-- ลบ policy เก่าแล้วสร้างใหม่ (idempotent)
do $$ begin
  -- system_settings: public read, service_role write (ดูไฟล์แยก)
  drop policy if exists "Allow public read system_settings" on public.system_settings;
  create policy "Allow public read system_settings" on public.system_settings for select using (true);
  drop policy if exists "Allow upsert system_settings" on public.system_settings;
  create policy "Allow upsert system_settings" on public.system_settings for all using (true) with check (true);

  -- users: public read (ต้อง login ฝั่ง app), service_role all
  drop policy if exists "Allow public read users" on public.users;
  create policy "Allow public read users" on public.users for select using (true);
  drop policy if exists "Allow all users" on public.users;
  create policy "Allow all users" on public.users for all using (true) with check (true);

  -- steps_log, sweet_free, อื่นๆ: เปิดหมดก่อน ค่อยล็อกทีหลัง
  drop policy if exists "Allow all steps_log" on public.steps_log;
  create policy "Allow all steps_log" on public.steps_log for all using (true) with check (true);
  drop policy if exists "Allow all sweet_free" on public.sweet_free;
  create policy "Allow all sweet_free" on public.sweet_free for all using (true) with check (true);
  drop policy if exists "Allow all baseline" on public.baseline_records;
  create policy "Allow all baseline" on public.baseline_records for all using (true) with check (true);
  drop policy if exists "Allow all weight_after" on public.weight_after_records;
  create policy "Allow all weight_after" on public.weight_after_records for all using (true) with check (true);
  drop policy if exists "Allow all project_settings" on public.project_settings;
  create policy "Allow all project_settings" on public.project_settings for all using (true) with check (true);
  drop policy if exists "Allow all google_fit_links" on public.google_fit_links;
  create policy "Allow all google_fit_links" on public.google_fit_links for all using (true) with check (true);
end $$;

